from __future__ import annotations

import math
from collections.abc import Sequence

import numpy as np


def _finite_values(
    values: Sequence[float],
) -> np.ndarray:
    array = np.asarray(
        values,
        dtype=np.float64,
    )

    if array.ndim != 1:
        raise ValueError(
            "Gradient statistics require "
            "one-dimensional values."
        )

    return array[
        np.isfinite(
            array
        )
    ]


def excess_kurtosis(
    values: Sequence[float],
) -> float:
    """
    Population excess kurtosis.

    This is a descriptive tail diagnostic, not a
    formal test of finite higher moments.
    """

    array = _finite_values(
        values
    )

    if array.size < 4:
        return float(
            "nan"
        )

    mean_value = float(
        np.mean(
            array
        )
    )

    standard_deviation = float(
        np.std(
            array,
            ddof=0,
        )
    )

    if standard_deviation <= 0.0:
        return 0.0

    standardized = (
        array - mean_value
    ) / standard_deviation

    return float(
        np.mean(
            standardized ** 4
        )
        - 3.0
    )


def hill_tail_index(
    values: Sequence[float],
    *,
    tail_fraction: float,
    minimum_tail: int = 20,
) -> float:
    """
    Hill estimator for the positive upper tail.

    Smaller alpha indicates a heavier empirical tail.

    This estimator is exploratory here because gradient
    observations are dependent and generated by an
    adaptive optimization process.
    """

    if not (
        0.0
        < tail_fraction
        < 1.0
    ):
        raise ValueError(
            "tail_fraction must lie in (0, 1)."
        )

    array = _finite_values(
        values
    )

    array = array[
        array > 0.0
    ]

    n = int(
        array.size
    )

    if n < (
        minimum_tail + 2
    ):
        return float(
            "nan"
        )

    array.sort()

    k = max(
        minimum_tail,
        int(
            math.floor(
                n
                * tail_fraction
            )
        ),
    )

    k = min(
        k,
        n - 1,
    )

    threshold = float(
        array[
            -(k + 1)
        ]
    )

    if threshold <= 0.0:
        return float(
            "nan"
        )

    upper = array[
        -k:
    ]

    mean_log_excess = float(
        np.mean(
            np.log(
                upper
                / threshold
            )
        )
    )

    if mean_log_excess <= 0.0:
        return float(
            "inf"
        )

    return (
        1.0
        / mean_log_excess
    )


def distribution_summary(
    values: Sequence[float],
) -> dict[str, float | int]:
    array = _finite_values(
        values
    )

    if array.size == 0:
        raise ValueError(
            "No finite observations."
        )

    median = float(
        np.quantile(
            array,
            0.50,
        )
    )

    p90 = float(
        np.quantile(
            array,
            0.90,
        )
    )

    p95 = float(
        np.quantile(
            array,
            0.95,
        )
    )

    p99 = float(
        np.quantile(
            array,
            0.99,
        )
    )

    p995 = float(
        np.quantile(
            array,
            0.995,
        )
    )

    maximum = float(
        np.max(
            array
        )
    )

    return {
        "count":
            int(
                array.size
            ),
        "mean":
            float(
                np.mean(
                    array
                )
            ),
        "standard_deviation":
            float(
                np.std(
                    array,
                    ddof=0,
                )
            ),
        "median":
            median,
        "p90":
            p90,
        "p95":
            p95,
        "p99":
            p99,
        "p995":
            p995,
        "maximum":
            maximum,
        "p99_to_median":
            (
                p99
                / median
                if median > 0.0
                else float(
                    "nan"
                )
            ),
        "max_to_p99":
            (
                maximum
                / p99
                if p99 > 0.0
                else float(
                    "nan"
                )
            ),
        "excess_kurtosis":
            excess_kurtosis(
                array
            ),
        "hill_alpha_05":
            hill_tail_index(
                array,
                tail_fraction=0.05,
            ),
        "hill_alpha_10":
            hill_tail_index(
                array,
                tail_fraction=0.10,
            ),
    }


def _average_ranks(
    values: np.ndarray,
) -> np.ndarray:
    order = np.argsort(
        values,
        kind="mergesort",
    )

    ranks = np.empty(
        values.size,
        dtype=np.float64,
    )

    start = 0

    while start < values.size:
        end = start + 1

        while (
            end < values.size
            and
            values[
                order[
                    end
                ]
            ]
            == values[
                order[
                    start
                ]
            ]
        ):
            end += 1

        average_rank = (
            start
            + end
            - 1
        ) / 2.0

        ranks[
            order[
                start:end
            ]
        ] = average_rank

        start = end

    return ranks


def correlation(
    first: Sequence[float],
    second: Sequence[float],
    *,
    method: str,
) -> float:
    x = np.asarray(
        first,
        dtype=np.float64,
    )

    y = np.asarray(
        second,
        dtype=np.float64,
    )

    if (
        x.ndim != 1
        or y.ndim != 1
        or x.size != y.size
    ):
        raise ValueError(
            "Correlation inputs must be equal-length "
            "one-dimensional arrays."
        )

    mask = (
        np.isfinite(
            x
        )
        & np.isfinite(
            y
        )
    )

    x = x[
        mask
    ]

    y = y[
        mask
    ]

    if x.size < 2:
        return float(
            "nan"
        )

    if method == "spearman":
        x = _average_ranks(
            x
        )

        y = _average_ranks(
            y
        )

    elif method != "pearson":
        raise ValueError(
            "method must be 'pearson' "
            "or 'spearman'."
        )

    if (
        np.std(
            x
        )
        <= 0.0
        or
        np.std(
            y
        )
        <= 0.0
    ):
        return float(
            "nan"
        )

    return float(
        np.corrcoef(
            x,
            y,
        )[
            0,
            1,
        ]
    )
